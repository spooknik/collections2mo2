"""Build the MO2 profile (mod order, plugin order, ini files) from install.json.

Consumes the `install.json` written by the installer step (see the module docstring
in `installer.py`) plus the original `collection.json` manifest, and writes a
portable MO2 instance under `--mo2-dir`: `ModOrganizer.ini`, `downloads/`,
`overwrite/`, and `profiles/<profile>/{modlist,plugins,loadorder}.txt` +
`settings.ini`. Mod order is derived from the manifest's install `phase` plus any
`modRules` that resolve to two mods actually present in the collection; plugin
order is derived from mod order plus the manifest's own `plugins[]` load order.
"""

